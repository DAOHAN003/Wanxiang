#!/usr/bin/env python3
"""Attach deterministic source-revision metadata to the generated demo payload.

The SDK remains responsible for simulation output. This helper only records the
repository revision and workflow that produced the static artifact.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from typing import Any


def annotate(data: Any, *, repository: str | None, revision: str | None,
             workflow: str | None) -> dict[str, Any]:
    if not isinstance(data, dict):
        raise ValueError("demo payload must be a JSON object")
    if data.get("generated_by") != "wanxiang_sdk::WorldModel":
        raise ValueError("refusing to annotate data not generated by wanxiang_sdk::WorldModel")
    if not isinstance(data.get("baseline"), dict) or not isinstance(data.get("altered"), dict):
        raise ValueError("demo payload must contain paired baseline and altered snapshots")
    if not revision:
        data["build"] = {
            "source": "local",
            "revision": None,
            "repository": repository,
            "workflow": workflow,
        }
    else:
        data["build"] = {
            "source": "github-actions",
            "revision": revision,
            "repository": repository,
            "workflow": workflow,
        }
    return data


def main() -> int:
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("site/data/demo.json")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        annotated = annotate(
            data,
            repository=os.environ.get("GITHUB_REPOSITORY"),
            revision=os.environ.get("GITHUB_SHA"),
            workflow=os.environ.get("GITHUB_WORKFLOW"),
        )
        path.write_text(json.dumps(annotated, ensure_ascii=False, separators=(",", ":")) + "\n",
                        encoding="utf-8")
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"Unable to annotate Wanxiang demo build metadata: {exc}", file=sys.stderr)
        return 1
    print(f"Attached build metadata to {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
